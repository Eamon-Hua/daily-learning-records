USE dbtest22;

DELIMITER //

-- IF分支
CREATE PROCEDURE IF演示(IN age INT)
BEGIN
IF age<18 THEN
SELECT '未成年';
ELSEIF age<60 THEN
SELECT '成年人';
ELSE
SELECT '老年';
END IF;
END //

CALL IF演示(15) //
CALL IF演示(30) //
CALL IF演示(70) //

-- CASE等值判断
CREATE PROCEDURE CASE等值(IN d INT)
BEGIN
CASE d
WHEN 10 THEN SELECT '10号部门';
WHEN 20 THEN SELECT '20号部门';
ELSE SELECT '其他部门';
END CASE;
END //

CALL CASE等值(10) //
CALL CASE等值(99) //

-- CASE条件判断
CREATE PROCEDURE CASE条件(IN score INT)
BEGIN
CASE
WHEN score>=90 THEN SELECT '优秀';
WHEN score>=60 THEN SELECT '及格';
ELSE SELECT '不及格';
END CASE;
END //

CALL CASE条件(95) //
CALL CASE条件(70) //
CALL CASE条件(50) //

-- WHILE求1到n的和
CREATE PROCEDURE WHILE求和(IN n INT,OUT s INT)
BEGIN
DECLARE i INT DEFAULT 1;
SET s=0;
WHILE i<=n DO
SET s=s+i;
SET i=i+1;
END WHILE;
END //

CALL WHILE求和(100,@s1) //
SELECT @s1 //

-- REPEAT，至少跑一次，UNTIL条件成立退出
CREATE PROCEDURE REPEAT求和(IN n INT,OUT s INT)
BEGIN
DECLARE i INT DEFAULT 1;
SET s=0;
REPEAT
SET s=s+i;
SET i=i+1;
UNTIL i>n END REPEAT;
END //

CALL REPEAT求和(0,@s2) //
SELECT @s2 //
-- n传0，REPEAT还是先加了一个1进来，输出1——这就是"至少跑一次"

-- LOOP必须配LEAVE，不然死循环
CREATE PROCEDURE LOOP求和(IN n INT,OUT s INT)
BEGIN
DECLARE i INT DEFAULT 1;
SET s=0;
myloop: LOOP
IF i>n THEN
LEAVE myloop;
END IF;
SET s=s+i;
SET i=i+1;
END LOOP myloop;
END //

CALL LOOP求和(100,@s3) //
SELECT @s3 //

-- LEAVE和ITERATE，跳过奇数求偶数和
CREATE PROCEDURE 偶数和(IN n INT,OUT s INT)
BEGIN
DECLARE i INT DEFAULT 0;
SET s=0;
addnum: LOOP
SET i=i+1;
IF i>n THEN LEAVE addnum; END IF;
IF i%2=1 THEN ITERATE addnum; END IF;
SET s=s+i;
END LOOP addnum;
END //

CALL 偶数和(100,@s4) //
SELECT @s4 //
-- 100以内偶数和2550

